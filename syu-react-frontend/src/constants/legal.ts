export const OFFICER_AFFILIATION = '삼육대학교 산학협력 연구 프로젝트팀';

/**
 * 처리방침에서 보호책임자 조항을 찾아내는 판별식.
 *
 * 조항 번호가 아니라 제목의 낱말로 찾는다 — 어드민에서 조항을 추가·삭제하면
 * 번호가 밀리기 때문이다. 이 판별식이 걸러 낸 조항의 본문은
 * buildOfficerSectionBody()가 통째로 다시 만든다(성명·연락처가 두 곳에
 * 적히지 않게 하려는 것).
 */
export function isOfficerSection(heading: string): boolean {
  return heading.includes('보호책임자');
}

/**
 * 처리방침 제10조 본문을 성명·연락처로부터 만든다.
 *
 * 조항 본문에 주소를 직접 적지 않고 이 함수를 거치는 이유는, 운영 정보가
 * DB(settings/legal)로 나가면서 **같은 사실이 조항 산문과 구조화 필드 두
 * 곳에 살게 됐기** 때문이다. 두 곳을 각각 고치게 두면 어느 한쪽만 바뀌어
 * 화면에 옛 담당자가 남는다 — 본문을 항상 필드에서 파생시켜 그 경로를 막는다.
 */
export function buildOfficerSectionBody(params: {
  officerName: string;
  contactEmail: string;
  affiliation?: string;
}): string {
  const { officerName, contactEmail, affiliation = OFFICER_AFFILIATION } = params;
  return [
    '개인정보 처리에 관한 문의, 불만 처리, 피해 구제 요청은 아래 보호책임자에게 연락해 주시기 바랍니다.',
    `- 성명: ${officerName}`,
    `- 소속: ${affiliation}`,
    `- 연락처: ${contactEmail}`,
  ].join('\n');
}

export interface LegalSection {
  /** 조항 제목 — 본문 첫 줄에 그대로 노출된다 */
  heading: string;
  /** 조항 본문. 줄바꿈은 \n 으로 표기한다 */
  body: string;
}

export interface LegalDocument {
  /** 마이페이지 메뉴 라벨이자 모달 제목 (단일 출처) */
  title: string;
  sections: LegalSection[];
}

